        // ------------------------------------------------------------------
        // The exe-side view of the report the generated module writes into.
        // The module gets the SAME definition (kReportHeader below, written into
        // the project as src/l02/L02Report.h). structSize is the drift guard:
        // the module stores its sizeof on first stamp; the harness compares.
        // ------------------------------------------------------------------
        struct L02Report
        {
            std::atomic<long long> seq{0};
            std::atomic<long long> seqLastDtor{0};
            std::atomic<long long> dtorCalls{0};
            std::atomic<long long> structSize{0};
        };

        const char* kReportHeader = R"(#pragma once
// L02Report.h — generated by the WO-07 L02 harness. Exe-owned report the module's
// component destructor stamps into (pointer handed over by COSMIC_L02_REPORT).
#include <atomic>
#include <cstdlib>
struct L02Report
{
    std::atomic<long long> seq{0};
    std::atomic<long long> seqLastDtor{0};
    std::atomic<long long> dtorCalls{0};
    std::atomic<long long> structSize{0};
};
inline L02Report* L02_Report()
{
    static L02Report* r = []() -> L02Report* {
        char* v = nullptr; size_t n = 0;
        _dupenv_s(&v, &n, "COSMIC_L02_REPORT");
        L02Report* p = v ? reinterpret_cast<L02Report*>(_strtoui64(v, nullptr, 16)) : nullptr;
        free(v);
        return p;
    }();
    return r;
}
inline void L02_StampDtor()
{
    if (L02Report* r = L02_Report())
    {
        r->structSize = (long long)sizeof(L02Report);
        ++r->dtorCalls;
        r->seqLastDtor = ++r->seq;
    }
}
)";

        // ------------------------------------------------------------------
        // Reflected-surface variants. One field change per transition.
        // ------------------------------------------------------------------
        using Cosmic::Reflect::FieldKind;
        using Cosmic::Reflect::FieldValue;

        struct FieldSpec
        {
            const char* name;
            FieldKind   kind;
            const char* cxxType;
            const char* cxxDefault;   // C++ initializer text
            FieldValue  def;          // the same default, as the harness expects it
        };
        struct Variant
        {
            const char* label;                 // what changed vs. the previous variant
            std::vector<FieldSpec> comp;       // L02Component
            std::vector<FieldSpec> extra;      // L02Extra (empty == type absent)
            std::vector<FieldSpec> script;     // L02Script
        };

        // C++ float literal text: "%g" alone yields "1f" for integral values, which is not a literal.
        std::string Lit(float v) { char b[64]; std::snprintf(b, sizeof(b), "%g", v); std::string s = b; if (s.find_first_of(".e") == std::string::npos) s += ".0"; return s + "f"; }
        FieldSpec F(const char* n, float v)             { std::string b = Lit(v); return { n, FieldKind::Float,  "float",       _strdup(b.c_str()), FieldValue{ v } }; }
        FieldSpec I(const char* n, int v)               { char b[64]; std::snprintf(b, sizeof(b), "%d", v);  return { n, FieldKind::Int32,  "int",         _strdup(b), FieldValue{ (int32_t)v } }; }
        FieldSpec B(const char* n, bool v)              { return { n, FieldKind::Bool,   "bool",        v ? "true" : "false", FieldValue{ v } }; }
        FieldSpec S(const char* n, const char* v)       { char b[96]; std::snprintf(b, sizeof(b), "\"%s\"", v); return { n, FieldKind::String, "std::string", _strdup(b), FieldValue{ std::string(v) } }; }
        FieldSpec V3(const char* n, float x, float y, float z) { std::string b = "{" + Lit(x) + ", " + Lit(y) + ", " + Lit(z) + "}"; return { n, FieldKind::Vec3, "glm::vec3", _strdup(b.c_str()), FieldValue{ glm::vec3(x, y, z) } }; }
        FieldSpec V4(const char* n, float x, float y, float z, float w) { std::string b = "{" + Lit(x) + ", " + Lit(y) + ", " + Lit(z) + ", " + Lit(w) + "}"; return { n, FieldKind::Vec4, "glm::vec4", _strdup(b.c_str()), FieldValue{ glm::vec4(x, y, z, w) } }; }

        std::vector<Variant> BuildVariants()
        {
            std::vector<Variant> v;
            const std::vector<FieldSpec> s0 = { F("Rate", 1.0f), I("Loops", 2) };
            const std::vector<FieldSpec> s1 = { F("Rate", 1.0f), I("Loops", 2), F("Bias", 0.25f) };
            const std::vector<FieldSpec> s2 = { F("Rate", 1.0f), F("Bias", 0.25f) };
            // V0: baseline
            v.push_back({ "baseline", { F("Speed", 1.5f), I("Count", 3), B("Enabled", true), S("Label", "alpha"), V3("Offset", 1, 2, 3) }, {}, s0 });
            // V1: add float Mass
            v.push_back({ "add field Mass:float", { F("Speed", 1.5f), I("Count", 3), B("Enabled", true), S("Label", "alpha"), V3("Offset", 1, 2, 3), F("Mass", 2.0f) }, {}, s0 });
            // V2: retype Count int -> float
            v.push_back({ "retype Count int->float", { F("Speed", 1.5f), F("Count", 3.0f), B("Enabled", true), S("Label", "alpha"), V3("Offset", 1, 2, 3), F("Mass", 2.0f) }, {}, s0 });
            // V3: rename Label -> Name (new default "beta")
            v.push_back({ "rename Label->Name", { F("Speed", 1.5f), F("Count", 3.0f), B("Enabled", true), S("Name", "beta"), V3("Offset", 1, 2, 3), F("Mass", 2.0f) }, {}, s0 });
            // V4: remove Offset
            v.push_back({ "remove field Offset", { F("Speed", 1.5f), F("Count", 3.0f), B("Enabled", true), S("Name", "beta"), F("Mass", 2.0f) }, {}, s0 });
            // V5: add vec4 Tint + script gains Bias
            v.push_back({ "add field Tint:vec4 + script field Bias", { F("Speed", 1.5f), F("Count", 3.0f), B("Enabled", true), S("Name", "beta"), F("Mass", 2.0f), V4("Tint", 1, 0, 0, 1) }, {}, s1 });
            // V6: default changes (Enabled true->false, Mass 2->4)
            v.push_back({ "change defaults Enabled->false, Mass->4", { F("Speed", 1.5f), F("Count", 3.0f), B("Enabled", false), S("Name", "beta"), F("Mass", 4.0f), V4("Tint", 1, 0, 0, 1) }, {}, s1 });
            // V7: add int Extra
            v.push_back({ "add field Extra:int", { F("Speed", 1.5f), F("Count", 3.0f), B("Enabled", false), S("Name", "beta"), F("Mass", 4.0f), V4("Tint", 1, 0, 0, 1), I("Extra", 7) }, {}, s1 });
            // V8: remove Mass
            v.push_back({ "remove field Mass", { F("Speed", 1.5f), F("Count", 3.0f), B("Enabled", false), S("Name", "beta"), V4("Tint", 1, 0, 0, 1), I("Extra", 7) }, {}, s1 });
            // V9: retype Speed float -> int + script loses Loops
            v.push_back({ "retype Speed float->int + script remove Loops", { I("Speed", 2), F("Count", 3.0f), B("Enabled", false), S("Name", "beta"), V4("Tint", 1, 0, 0, 1), I("Extra", 7) }, {}, s2 });
            // V10: add a second component type L02Extra
            v.push_back({ "add component type L02Extra", { I("Speed", 2), F("Count", 3.0f), B("Enabled", false), S("Name", "beta"), V4("Tint", 1, 0, 0, 1), I("Extra", 7) }, { F("Gain", 0.5f), I("Mode", 1) }, s2 });
            // V11: Name default -> "gamma", remove Tint
            v.push_back({ "change default Name->gamma + remove field Tint", { I("Speed", 2), F("Count", 3.0f), B("Enabled", false), S("Name", "gamma"), I("Extra", 7) }, { F("Gain", 0.5f), I("Mode", 1) }, s2 });
            // V12: remove component type L02Extra
            v.push_back({ "remove component type L02Extra", { I("Speed", 2), F("Count", 3.0f), B("Enabled", false), S("Name", "gamma"), I("Extra", 7) }, {}, s2 });
            return v;
        }

        // Which variant a cycle uses; 4 cycles per variant so every transition is
        // reloaded several times after the change (13 variants x 4 = 52 cycles).
        int VariantFor(int cycle, int variantCount) { const int v = (cycle - 1) / 4; return v < variantCount ? v : variantCount - 1; }

        // Failure cycles (overridable through COSMIC_L02_COMPILEFAIL_CYCLE / _LOADFAIL_CYCLE so
        // a short failing-before run can reach them early).
        int kCompileFailCycle = 25;   // deliberate syntax error
        int kLoadFailCycle    = 41;   // builds, but exports no CosmicModule_Register

