// L02ModuleReloadSelfTest.cpp — WO-07 (2D stability): the editor game-module reload
// acceptance (L02), driven inside the REAL Starforge editor.
//
// This is the SECOND DLL lifecycle (distinct from the Application runtime plugin
// L01 covers): StarforgeApp::BuildScripts -> BuildRunner (real cmake configure +
// build of the scaffolded project) -> StarforgeApp::ReloadModule -> GameModule
// (serialize edit scene, stop Play, clear selection/undo, Scene.reset() while the
// OLD module is still mapped, FreeLibrary, LoadLibrary the NEW _hotN DLL, restore).
//
// When armed by COSMIC_L02_SELFTEST=<result-file> the harness, from inside the
// editor:
//   1. scaffolds a REAL project through the editor's own NewProjectAt (the shipped
//      template: CMakeLists + src/ + scenes/Main.cscene), then adds a custom
//      REFLECTED component (CS_COMPONENT L02Component) and a script (L02Script);
//   2. runs N build cycles. EVERY cycle rewrites Module.cpp (a fresh build stamp the
//      harness reads back from the loaded DLL, so an unchanged DLL can never pass)
//      and, on a fixed schedule, changes the reflected surface — add / remove /
//      rename / retype a field, change a default, add / remove a whole component
//      type (13 variants => 12 reflected-field changes across the run);
//   3. after every successful reload it asserts, through the REFLECTION registry
//      (not the serializer under test): the preserved field values equal the
//      harness's own expectation table, new fields read the new module's default,
//      the descriptor field list equals the variant EXACTLY (no accumulation, no
//      loss), the script descriptor matches, the probe entity's UUID/Tag/Transform
//      survived, Play is stopped, selection + undo are cleared, the old DLL was
//      still mapped when the module-typed destructors ran (report stamped from the
//      DLL's own destructor) and unmapped afterwards, and the new DLL is the one
//      just built;
//   4. includes one deliberate COMPILE failure and one deliberate MODULE-LOAD
//      failure (a DLL that builds but exports no CosmicModule_Register) — the
//      editor must keep the current module / keep the scene data and stay live;
//   5. saves the scene through the real Save path so the runner wrapper can parse
//      Main.cscene OUT OF PROCESS (an independent oracle) against the expected
//      final values the harness writes next to the result.
//
// Verdict -> exit code (the acceptance runner's oracle): PASS -> graceful close,
// main() returns 0; FAIL -> quick_exit(1). A JSON result is always written.

