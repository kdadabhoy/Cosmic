    inline std::string FwReplaceAll(std::string s, const std::string& from, const std::string& to)
    {
        if (from.empty()) return s;
        size_t pos = 0;
        while ((pos = s.find(from, pos)) != std::string::npos)
        {
            s.replace(pos, from.size(), to);
            pos += to.size();
        }
        return s;
    }

    // Shared boilerplate appended to the single-ESC decode sketches.
    inline const char* FwKissHelpers()
    {
        return R"FW(uint8_t update_crc8(uint8_t crc, uint8_t seed)
{
    uint8_t u = crc ^ seed;
    for (int i = 0; i < 8; i++) u = (u & 0x80) ? (0x07 ^ (u << 1)) : (u << 1);
    return u;
}
uint8_t get_crc8(uint8_t* b, uint8_t size)
{
    uint8_t crc = 0;
    for (uint8_t i = 0; i < size; i++) crc = update_crc8(b[i], crc);
    return crc;
}
bool parseESC(uint8_t* b, ESC_Data& d)
{
    if (get_crc8(b, 9) != b[9]) return false;
    d.temp = b[0];
    d.voltage = (b[1] << 8) | b[2]; d.current = (b[3] << 8) | b[4];
    d.consumption = (b[5] << 8) | b[6]; d.erpm = (b[7] << 8) | b[8];
    d.valid = true; return true;
}
void broadcastPrint(const char* msg)
{
    Serial.print(msg);
    if (SerialBT.connected()) SerialBT.print(msg);
}
void sendFrame(char side, const ESC_Data& d)
{
    char payload[48];
    int n = snprintf(payload, sizeof(payload), "%c,%u,%u,%u,%u,%u",
                     side, (unsigned)d.temp, (unsigned)d.voltage, (unsigned)d.current,
                     (unsigned)d.consumption, (unsigned)d.erpm);
    if (n <= 0) return;
    uint8_t crc = 0;
    for (int i = 0; i < n; i++) crc ^= (uint8_t)payload[i];
    char frame[64];
    snprintf(frame, sizeof(frame), "$%s*%02X\n", payload, crc);
    broadcastPrint(frame);
}
)FW";
    }

    // ---- 1. Single drive ESC (pin + side tag) ----
    inline std::string BuildSingleDrive(int drivePin, char side, const std::string& btName)
    {
        std::string s = R"FW(// sf_test_single_drive.ino — SF_TelemTest: single DRIVE ESC test
// Generated by the app. Wire one drive ESC telem -> GPIO {{DRIVE_PIN}} (UART1) + GND.
#include <Arduino.h>
#include "BluetoothSerial.h"

#define BT_DEVICE_NAME  "{{BT_NAME}}"
#define DRIVE_TLM_PIN   {{DRIVE_PIN}}    // drive ESC telemetry -> UART1 RX
#define DRIVE_SIDE      '{{DRIVE_SIDE}}'  // 'R' or 'L' — matches the app's Right/Left toggle
#define ESC_BAUD        115200
#define STALE_MS        600

HardwareSerial  SerialDrive(1);   // UART1
BluetoothSerial SerialBT;

struct ESC_Data { uint8_t temp = 0; uint16_t voltage = 0, current = 0, consumption = 0, erpm = 0; bool valid = false; };
ESC_Data      tlm;
uint8_t       buf[10];
unsigned long lastMs = 0, lastHeartbeat = 0;

)FW";
        s += FwKissHelpers();
        s += R"FW(
bool serviceSide(Stream& port)
{
    if (port.available() > 50) while (port.available()) port.read();
    if (port.available() >= 10)
    {
        port.readBytes(buf, 10);
        if (parseESC(buf, tlm)) { sendFrame(DRIVE_SIDE, tlm); tlm.valid = false; return true; }
    }
    return false;
}

void setup()
{
    Serial.begin(115200);
    delay(500);
    SerialDrive.begin(ESC_BAUD, SERIAL_8N1, DRIVE_TLM_PIN, -1, false);
    SerialBT.begin(BT_DEVICE_NAME);
    Serial.printf("# SF_TelemTest single-drive online (pin %d, side %c)\n", DRIVE_TLM_PIN, DRIVE_SIDE);
}

void loop()
{
    if (serviceSide(SerialDrive)) lastMs = millis();
    if (millis() - lastHeartbeat > 1000)
    {
        const bool ok = (millis() - lastMs) < STALE_MS;
        char s[48];
        snprintf(s, sizeof(s), "# %c=%s bt=%s\n", DRIVE_SIDE, ok ? "ok" : "ERR", SerialBT.connected() ? "yes" : "no");
        broadcastPrint(s);
        lastHeartbeat = millis();
    }
}
)FW";
        s = FwReplaceAll(s, "{{DRIVE_PIN}}",  std::to_string(drivePin));
        s = FwReplaceAll(s, "{{DRIVE_SIDE}}", std::string(1, side));
        s = FwReplaceAll(s, "{{BT_NAME}}",    btName);
        return s;
    }

