    // ---- 4. Raw sniffer (no decode; reports byte activity per wire) ----
    inline std::string BuildSniffer(int rightPin, int leftPin, int weaponPin, const std::string& btName)
    {
        std::string s = R"FW(// sf_test_sniffer.ino — SF_TelemTest: raw telemetry SNIFFER
// Generated by the app. Counts raw bytes on each wire (valid or not) and reports
// SNIFF,<tag>,<interval>,<total>,<hex> every ~150 ms.
// RIGHT -> GPIO {{RIGHT_PIN}} (UART1), LEFT -> GPIO {{LEFT_PIN}} (UART2),
// WEAPON -> GPIO {{WEAPON_PIN}} (UART0 RX remapped; TX on GPIO1) + GND.
#include <Arduino.h>
#include "BluetoothSerial.h"

#define BT_DEVICE_NAME  "{{BT_NAME}}"
#define RIGHT_TLM_PIN   {{RIGHT_PIN}}
#define LEFT_TLM_PIN    {{LEFT_PIN}}
#define WEAPON_TLM_PIN  {{WEAPON_PIN}}
#define ESC_BAUD        115200
#define REPORT_MS       150

HardwareSerial  SerialRight(1);   // UART1
HardwareSerial  SerialLeft(2);    // UART2
BluetoothSerial SerialBT;

enum { R = 0, L = 1, W = 2, N = 3 };
const char TAG[N] = { 'R', 'L', 'W' };

unsigned long total[N]    = { 0, 0, 0 };
unsigned long interval[N] = { 0, 0, 0 };
char          sample[N][24];
int           sampleLen[N] = { 0, 0, 0 };
unsigned long lastReport = 0;

void broadcastPrint(const char* msg)
{
    Serial.print(msg);
    if (SerialBT.connected()) SerialBT.print(msg);
}

void drain(Stream& port, int i)
{
    while (port.available())
    {
        int b = port.read();
        if (b < 0) break;
        total[i]++; interval[i]++;
        if (sampleLen[i] < 16)
        {
            char h[3]; snprintf(h, sizeof(h), "%02X", (uint8_t)b);
            sample[i][sampleLen[i]++] = h[0];
            sample[i][sampleLen[i]++] = h[1];
            sample[i][sampleLen[i]]   = 0;
        }
    }
}

void setup()
{
    Serial.begin(115200, SERIAL_8N1, WEAPON_TLM_PIN, 1);  // weapon RX remapped, USB TX kept
    delay(1000);
    SerialRight.begin(ESC_BAUD, SERIAL_8N1, RIGHT_TLM_PIN, -1, false);
    SerialLeft.begin(ESC_BAUD, SERIAL_8N1, LEFT_TLM_PIN,  -1, false);
    SerialBT.begin(BT_DEVICE_NAME);
    Serial.printf("# SF_TelemTest sniffer online (R %d / L %d / W %d)\n", RIGHT_TLM_PIN, LEFT_TLM_PIN, WEAPON_TLM_PIN);
}

void loop()
{
    drain(SerialRight, R);
    drain(SerialLeft,  L);
    drain(Serial,      W);

    if (millis() - lastReport >= REPORT_MS)
    {
        for (int i = 0; i < N; i++)
        {
            char line[64];
            snprintf(line, sizeof(line), "SNIFF,%c,%lu,%lu,%s\n",
                     TAG[i], interval[i], total[i], sampleLen[i] ? sample[i] : "-");
            broadcastPrint(line);
            interval[i] = 0; sampleLen[i] = 0; sample[i][0] = 0;
        }
        lastReport = millis();
    }
}
)FW";
        s = FwReplaceAll(s, "{{RIGHT_PIN}}",  std::to_string(rightPin));
        s = FwReplaceAll(s, "{{LEFT_PIN}}",   std::to_string(leftPin));
        s = FwReplaceAll(s, "{{WEAPON_PIN}}", std::to_string(weaponPin));
        s = FwReplaceAll(s, "{{BT_NAME}}",    btName);
        return s;
    }

